"""
Generates /lua/ui/lobby/data/coopnpccolors.lua from a checkout of the
FAForever co-op maps repository (https://github.com/FAForever/fa-coop-maps
or a local clone).

For every mission it collects the RGB colors the mission script assigns to
non-player armies (via the `ScenarioFramework.Set*Color` helpers, direct
`SetArmyColor` calls and the `local colors = { ['Army'] = {r, g, b} }`
pattern). The lobby uses this table to keep players from picking a color
that is (nearly) the same as one of the mission's NPC armies.

Usage:
    python scripts/GenerateCoopNpcColors.py <path-to-coop-maps-repo>
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FA_ROOT = os.path.dirname(HERE)
OUT = os.path.join(FA_ROOT, 'lua', 'ui', 'lobby', 'data', 'coopnpccolors.lua')

NUM = r'-?\d+(?:\.\d+)?'


def read(path):
    with open(path, 'r', encoding='latin-1') as f:
        return f.read()


def framework_colors():
    """name of `ScenarioFramework.Set*Color` helper -> (r, g, b)"""
    src = read(os.path.join(FA_ROOT, 'lua', 'ScenarioFramework.lua'))
    out = {}
    pattern = re.compile(
        r'function\s+(Set\w*Color)\s*\(\s*army\s*\)\s*SetArmyColor\s*\(\s*army\s*,\s*(' + NUM + r')\s*,\s*(' + NUM + r')\s*,\s*(' + NUM + r')\s*\)')
    for name, r, g, b in pattern.findall(src):
        out[name] = (int(float(r)), int(float(g)), int(float(b)))
    return out


def scenario_armies(folder):
    """army names in index order (1-based) from the scenario file"""
    for f in os.listdir(folder):
        if f.endswith('_scenario.lua'):
            src = read(os.path.join(folder, f))
            m = re.search(r"armies\s*=\s*\{([^}]*)\}", src)
            if m:
                return re.findall(r"'([^']+)'", m.group(1))
    return []


def resolve_army(arg, variables, armies):
    arg = arg.strip()
    if arg.startswith('ScenarioInfo.'):
        arg = arg[len('ScenarioInfo.'):]
    arg = arg.strip('\'"')
    if arg in variables:
        arg = variables[arg]
    if re.fullmatch(r'\d+', arg):
        index = int(arg)
        if 1 <= index <= len(armies):
            return armies[index - 1]
        return None
    if re.fullmatch(r'[A-Za-z_]\w*', arg):
        return arg
    return None


def mission_colors(folder, helpers):
    armies = scenario_armies(folder)
    colors = {}
    for f in os.listdir(folder):
        if not f.endswith('.lua') or f.endswith('_save.lua') or f.endswith('_strings.lua'):
            continue
        src = read(os.path.join(folder, f))

        # `local UEF = 3` / `ScenarioInfo.UEF = 3` / `local UEF = ScenarioInfo.UEF`
        variables = {}
        for name, value in re.findall(r'(?:local\s+|ScenarioInfo\.)(\w+)\s*=\s*(\d+|ScenarioInfo\.\w+|\'\w+\')\s*\n', src):
            variables[name] = value.replace('ScenarioInfo.', '').strip('\'')

        def add(army, rgb):
            if army and not army.startswith('Player'):
                colors.setdefault(army, set()).add(tuple(int(float(c)) for c in rgb))

        for helper, arg in re.findall(r'ScenarioFramework\.(Set\w*Color)\s*\(([^)]*)\)', src):
            if helper in helpers and helper != 'SetArmyColor':
                add(resolve_army(arg, variables, armies), helpers[helper])

        for arg, r, g, b in re.findall(
                r'SetArmyColor\s*\(\s*([^,()]+)\s*,\s*(' + NUM + r')\s*,\s*(' + NUM + r')\s*,\s*(' + NUM + r')\s*\)', src):
            add(resolve_army(arg, variables, armies), (r, g, b))

        for block in re.findall(r'colors\s*=\s*\{(.*?)\n\s*\}', src, re.S):
            for army, r, g, b in re.findall(
                    r"\[\s*'(\w+)'\s*\]\s*=\s*\{\s*(" + NUM + r")\s*,\s*(" + NUM + r")\s*,\s*(" + NUM + r")\s*\}", block):
                add(army, (r, g, b))
    return colors


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    repo = sys.argv[1]
    helpers = framework_colors()

    lines = [
        '-- Generated by /scripts/GenerateCoopNpcColors.py from the co-op maps repository.',
        '-- Do not edit by hand; re-run the script when missions change their army colors.',
        '--',
        '-- Map folder name (lower case, without `.vXXXX` suffix) -> RGB colors used by the',
        '-- mission\'s non-player armies. The lobby keeps players off palette colors that',
        '-- are too close to these. Maps can also declare `npcColors` themselves in',
        '-- `Configurations.standard` of their scenario file, which takes precedence.',
        '',
        '---@type table<string, number[][]>',
        'NpcColors = {',
    ]
    for name in sorted(os.listdir(repo)):
        folder = os.path.join(repo, name)
        if not os.path.isdir(folder) or name.startswith('.'):
            continue
        colors = mission_colors(folder, helpers)
        rgbs = sorted({rgb for s in colors.values() for rgb in s})
        if not rgbs:
            continue
        armies = ', '.join(sorted(colors))
        lines.append("    -- %s" % armies)
        lines.append("    ['%s'] = { %s }," % (
            name.lower(), ', '.join('{ %d, %d, %d }' % rgb for rgb in rgbs)))
    lines.append('}')
    lines.append('')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
